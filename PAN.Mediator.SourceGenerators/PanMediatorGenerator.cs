        private static HandlerInfo? GetHandler(GeneratorSyntaxContext context, CancellationToken cancellationToken)
        {
            var declaration = (TypeDeclarationSyntax)context.Node;

            if (context.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken) is not INamedTypeSymbol type)
                return null;

            if (type.TypeKind == TypeKind.Interface || type.IsAbstract || type.IsStatic)
                return null;

            foreach (var implemented in type.AllInterfaces)
            {
                if (implemented.Arity != 2)
                    continue;

                var definition = implemented.OriginalDefinition;
                if (definition.Name != HandlerInterfaceName)
                    continue;

                if (definition.ContainingNamespace.ToDisplayString() != HandlerNamespace)
                    continue;

                var requestType = implemented.TypeArguments[0];
                var responseType = implemented.TypeArguments[1];

                if (ContainsTypeParameter(requestType) || ContainsTypeParameter(responseType))
                    return null;

                if (requestType is not INamedTypeSymbol namedRequest || !IsAccessible(namedRequest))
                    return null;

                return new HandlerInfo(
                    requestType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                    responseType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            }

            return null;
        }

        private static bool ContainsTypeParameter(ITypeSymbol type)
        {
            switch (type)
            {
                case ITypeParameterSymbol _:
                    return true;

                case INamedTypeSymbol named:
                    foreach (var argument in named.TypeArguments)
                    {
                        if (ContainsTypeParameter(argument))
                            return true;
                    }

                    return false;

                case IArrayTypeSymbol array:
                    return ContainsTypeParameter(array.ElementType);

                case IPointerTypeSymbol pointer:
                    return ContainsTypeParameter(pointer.PointedAtType);

                default:
                    return false;
            }
        }

        private static bool IsAccessible(INamedTypeSymbol type)
        {
            for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            {
                switch (current.DeclaredAccessibility)
                {
                    case Accessibility.Private:
                    case Accessibility.Protected:
                    case Accessibility.ProtectedAndInternal:
                        return false;
                }
            }

            return true;
        }

